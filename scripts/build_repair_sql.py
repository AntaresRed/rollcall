#!/usr/bin/env python3
"""
Generate supabase/repair-stale-classes.sql from the catalogue.

    python3 scripts/build_repair_sql.py src/data/catalogue.json \
        supabase/repair-stale-classes.sql

Why this exists: saveTimetable used to only insert and delete, never update, so
a class row kept whatever the catalogue said on the day the student first
picked the course. When the institute corrected a course — most visibly a
course becoming post-mid — the saved row kept the old value, and the alert
sweep reads that column and nothing else. The app now patches drifted rows on
the next save, but that only helps once a student happens to re-save. This
repairs the rows already sitting in the database.

Matching is on (course_code, section, day_of_week, start_time), which is what
identifies one meeting of one section. Only catalogue-owned columns are
written: `muted` and `confirmed` belong to the student and are never touched,
and neither is `id`, which attendance is keyed to.
"""

import json
import sys

COLUMNS = (
    "course_code, section, day_of_week, start_time,\n"
    "                         term_phase, credits, total_classes, min_pct, room"
)

JOIN = """ where m.course_code = c.course_code
   and m.section     = c.section
   and m.day_of_week = c.day_of_week
   and m.start_time  = c.start_time"""

DRIFT = """   and (c.term_phase    is distinct from m.term_phase
     or c.credits       is distinct from m.credits
     or c.total_classes is distinct from m.total_classes
     or c.min_pct       is distinct from m.min_pct
     or c.room          is distinct from m.room)"""


def rows_from(catalogue):
    """One row per (course, section, meeting), de-duplicated.

    A course whose meetings carry their own phase — one that runs all term but
    meets on different days either side of mid-terms — must keep them, so the
    meeting's phase wins over the course's where it has one. That is the same
    rule CoursePicker applies when it saves.
    """
    seen = {}
    for course in catalogue["courses"]:
        for letter, meetings in (course.get("sections") or {}).items():
            for m in meetings:
                key = (course["code"], letter, m["day"], m["start"])
                row = (
                    course["code"], letter, m["day"], m["start"],
                    m.get("phase") or course.get("phase") or "full",
                    course.get("credits", 3.0),
                    course.get("total_classes", 20),
                    course.get("min_pct", 75),
                    course.get("venue") or None,
                )
                # Two meetings of one section at the same day and slot that
                # disagree would make the repair depend on iteration order.
                # Fail rather than pick one.
                if key in seen and seen[key] != row:
                    raise SystemExit(
                        f"conflicting catalogue entries for {key}:\n"
                        f"  {seen[key]}\n  {row}"
                    )
                seen[key] = row
    return [seen[k] for k in sorted(seen)]


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def build(catalogue):
    rows = rows_from(catalogue)
    values = ",\n".join(
        "    (" + ", ".join([
            lit(code), lit(section), str(day), f"time {lit(start)}", lit(phase),
            str(credits), str(total), str(pct), lit(venue),
        ]) + ")"
        for code, section, day, start, phase, credits, total, pct, venue in rows
    )
    cte = f"with catalogue_meetings ({COLUMNS}) as (\n  values\n{values}\n)"

    sql = f"""-- ============================================================
-- One-shot repair: bring saved class rows back in line with the catalogue.
--
-- GENERATED by scripts/build_repair_sql.py - do not edit by hand.
-- Regenerate after any catalogue rebuild.
--
-- Background: saveTimetable only ever inserted and deleted rows, never updated
-- them, so a row that survived a re-save kept whatever the catalogue said when
-- the student first picked the course. A course later corrected to post-mid
-- kept term_phase = 'full', and send-class-alerts reads that column and
-- nothing else - so its notifications fired from the first week of term. The
-- app now patches drifted rows on save; this fixes the ones already stored.
--
-- Safe to run more than once: it only writes rows that actually differ, and it
-- never touches `muted` or `confirmed`, which are the student's, or `id`,
-- which attendance is keyed to.
--
-- The two statements are self-contained - each carries its own copy of the
-- catalogue rather than sharing a temp table, so it does not matter whether
-- your SQL client runs them in one transaction, one session, or neither.
--
-- Run STEP 1 and read it. Run STEP 2 when the corrections look right.
-- ============================================================


-- ---------- STEP 1: what is currently wrong (changes nothing) ----------
{cte}
select c.course_code, c.section, c.subject,
       c.day_of_week, c.start_time,
       c.term_phase as saved_phase,   m.term_phase as correct_phase,
       c.credits    as saved_credits, m.credits    as correct_credits,
       c.room       as saved_room,    m.room       as correct_room,
       count(*) over () as rows_needing_repair
  from public.classes c
  join catalogue_meetings m
    on m.course_code = c.course_code
   and m.section     = c.section
   and m.day_of_week = c.day_of_week
   and m.start_time  = c.start_time
 where c.term_phase    is distinct from m.term_phase
    or c.credits       is distinct from m.credits
    or c.total_classes is distinct from m.total_classes
    or c.min_pct       is distinct from m.min_pct
    or c.room          is distinct from m.room
 order by c.course_code, c.day_of_week, c.start_time;


-- ---------- STEP 2: repair them ----------
{cte}
update public.classes c
   set term_phase    = m.term_phase,
       credits       = m.credits,
       total_classes = m.total_classes,
       min_pct       = m.min_pct,
       room          = m.room
  from catalogue_meetings m
{JOIN}
{DRIFT};


-- ---------- note on alert_log ----------
-- alert_log is the once-per-class-per-day dedupe. Rows already claimed today
-- are left alone on purpose: a course just corrected to post-mid should simply
-- stop firing, and nothing here needs to fire again. Clearing it would risk
-- re-sending alerts that have already gone out.
"""
    return sql, len(rows)


def main(src, dest):
    with open(src, encoding="utf-8") as fh:
        catalogue = json.load(fh)

    sql, count = build(catalogue)
    with open(dest, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(sql)

    print(f"{count} catalogue meetings -> {dest}")


if __name__ == "__main__":
    main(
        sys.argv[1] if len(sys.argv) > 1 else "src/data/catalogue.json",
        sys.argv[2] if len(sys.argv) > 2 else "supabase/repair-stale-classes.sql",
    )
